import { t } from '../i18n';

/** Unknown protocol names stay in folded diagnostics, never become UI copy. */
export function operationLabel(service: string, method: string): string {
  const domains: Record<string, string> = {
    documents: t('files'),
    terminal: t('terminal'),
    git: t('git'),
    tasks: t('tasks'),
    delivery: t('github delivery'),
    operations: t('review records'),
    inputs: t('recovered inputs'),
    events: t('activity'),
  };
  const actions: Record<string, string> = {
    read: t('read file'),
    save: t('save file'),
    applyEdits: t('apply file edits'),
    refresh: t('refresh'),
    resolveSource: t('locate source'),
    create: t('create'),
    restart: t('restart'),
    write: t('send terminal input'),
    resize: t('resize terminal'),
    signal: t('send signal to process'),
    close: t('close'),
    list: t('list items'),
    replay: t('read event history'),
    status: t('read status'),
    snapshot: t('read status'),
    applyPatch: t('apply patch'),
    conflictContinue: t('continue merge'),
    conflictAbort: t('abort merge'),
    diff: t('read differences'),
    stage: t('stage changes'),
    unstage: t('unstage changes'),
    applyHunk: t('apply change hunk'),
    discard: t('discard changes'),
    commit: t('create commit'),
    push: t('push commits'),
    branches: t('list branches'),
    continueMerge: t('continue merge'),
    abortMerge: t('abort merge'),
    start: t('start'),
    enqueue: t('queue tasks'),
    cancel: t('cancel task'),
    retry: t('retry'),
    events: t('read event history'),
    settings: t('update settings'),
    createIntegration: t('prepare to combine task changes'),
    mergeCandidates: t('integrate task changes'),
    review: t('record review'),
    artifacts: t('list task results'),
    readArtifact: t('read task result'),
    publish: t('publish pull request'),
    checks: t('read checks'),
    logs: t('read logs'),
    login: t('sign in to github'),
    ready: t('mark pull request ready'),
    resolve: t('resolve recovered input'),
  };
  return `${domains[service] ?? t('action')} · ${actions[method] ?? t('check the result')}`;
}
